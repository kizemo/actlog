    $combined.Add('LOCALE_ROW_EN=' + $(if ($enAbsent) { 'ABSENT' } else { $enRow }))
    $combined.Add('LOCALE_ZH_IS_ABSENT=' + $zhAbsent.ToString().ToLowerInvariant())
    $combined.Add('LOCALE_EN_IS_SET=' + (-not $enAbsent).ToString().ToLowerInvariant())
    $combined.Add('LOCALE_ROW_AFTER_RESTORE=' + $(if ($restored) { 'ABSENT' } else { $finalRow }))
    $combined.Add('LOCALE_RESTORED=' + $restored.ToString().ToLowerInvariant())
    $combined.Add('TASKBAR_BUTTON_NAME_ZH_AFTER_RESTORE=' + $zh2.Name)
    $combined.Add('CONTROL_XAPP=' + $ctl)
    $combined.Add('PROBE_VERDICT=' + $probe)
    $combined.Add('TASKBAR_BUTTON_NAME_ZH=' + $zh.Name)
    $combined.Add('TASKBAR_BUTTON_NAME_EN=' + $en.Name)

    [void](Write-Evidence -Path (Join-Path $ReportDir 'baseline_zh.txt') -Text (($zhBuf -join "`r`n") + "`r`n"))
    [void](Write-Evidence -Path (Join-Path $ReportDir 'baseline_en.txt') -Text (($enBuf -join "`r`n") + "`r`n"))
    [void](Write-Evidence -Path (Join-Path $ReportDir 'baseline_two_state.txt') -Text (($combined -join "`r`n") + "`r`n"))
}
else {
    # ---- single read --------------------------------------------------------
    if (-not $SkipStart) {
        [void](Stop-TargetProcs)
        if ($exeExists) {
            $p = Start-Process -FilePath $ExePath -PassThru
            $startedPids.Add($p.Id)
            Say ('START_PID=' + $p.Id)
        }
    }
    $read = Invoke-TaskbarRead -Lang $Language
    Say-Buttons $read
    $ctl = Get-ControlVerdict $read
    $probe = Get-ProbeVerdict $read $ctl

    Say 'TASKBAR_BUTTON_LANG=' + $Language
    Say ('TASKBAR_BUTTON_FOUND=' + $read.Found.ToString().ToLowerInvariant())
    Say ('TASKBAR_BUTTON_NAME=' + $read.Name)
    Say ('TASKBAR_BUTTON_PREFIX=' + $read.Prefix)
    Say ('TASKBAR_BUTTON_AUTOMATION_ID=' + $read.Id)
    Say ('TASKBAR_BUTTON_CLASS=' + $read.Class)
    Say ('TASKBAR_BUTTON_PINNED=' + $read.Pinned.ToString().ToLowerInvariant())
    Say ('WAIT_MS=' + $read.WaitMs)
    if ($Language -eq 'zh') {
        Say ('TASKBAR_BUTTON_NAME_ZH=' + $read.Name)
        Say ('TASKBAR_BUTTON_PREFIX_ZH=' + $read.Prefix)
    }
    if ($Language -eq 'en') {
        Say ('TASKBAR_BUTTON_NAME_EN=' + $read.Name)
        Say ('TASKBAR_BUTTON_PREFIX_EN=' + $read.Prefix)
    }
    Say ('CONTROL_XAPP=' + $ctl)
    Say ('PROBE_VERDICT=' + $probe)
    if ($probe -eq 'UNPROVEN') {
        Say 'PROBE_REASON=device not self-proven (control FAIL or target button missing); no product verdict is emitted'
    }
    if ($probe -eq 'FAIL') {
        Say 'PROBE_REASON=control PASS and target button located, but the name read back empty'
    }
    if ($probe -eq 'PASS') {
        Say 'PROBE_REASON=control PASS, target button located, name readable'
    }
}

# ------------------------------------------------------------------- teardown -
if (-not $KeepRunning) {
    $killed = Stop-TargetProcs
    foreach ($k in $killed) { $cleanedPids.Add($k) }
}
$after = @(Get-TargetProcs)
Say ('CLEANED_PIDS=' + (($cleanedPids | Sort-Object -Unique) -join ','))
Say ('ACTLOG_PROCS_AFTER=' + $after.Count)
foreach ($a in $after) { Say ('ACTLOG_PROC_LEFT=' + $a.Id + ' PATH=' + $a.Path) }

# The whole transcript goes to disk: every line above is in it, so a later
# reviewer can replay the reasoning without re-running the device.
$repPath = $Report
if ([string]::IsNullOrWhiteSpace($repPath)) {
    if ($TwoStateBaseline) { $repPath = Join-Path $ReportDir 'taskbar_button_name_two_state_run.txt' }
    else { $repPath = Join-Path $ReportDir 'taskbar_button_name_run.txt' }
}
[void](Write-Evidence -Path $repPath -Text (($script:out -join "`r`n") + "`r`n"))
Say 'PROBE_DONE=1'