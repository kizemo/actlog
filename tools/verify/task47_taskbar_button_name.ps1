# task47_taskbar_button_name.ps1 -- READ ONLY criterion: what name does the
# taskbar button of a given exe carry, and is the app controllable part of that
# name different between the zh and en UI language?
#
# WHY THIS FILE EXISTS (Task 47 W1c, deliverable A):
#   P-2 ("the taskbar text follows the language") was closed FAIL in W1 with an
#   ad hoc reading. The W1c baseline report (section D) then proved that no
#   machine-readable criterion for the taskbar BUTTON existed at all: zero
#   scripts emitted TASKBAR_BUTTON*, and the P-2 driver the W1 report named
#   (task47_p2_machine_check.ps1) was never written. This is that criterion.
#
# WHAT IT DOES:
#   * enumerates UI Automation descendants of Shell_TrayWnd and reports every
#     widget of type Button with its Name / AutomationId / ClassName / Rect;
#   * resolves the button that belongs to -ExePath. The shell names that button
#     in one of two shapes, and they mean different things:
#         Appid: D:\Program Files\actlog\actlog.exe   <- exe-path FALLBACK, i.e.
#                                                        the app declared no
#                                                        identity, so the shell
#                                                        shows the exe name
#         Appid: com.electron.Feishu                  <- the app DECLARED this
#                                                        AppUserModelID
#   * splits the button name into the shell-generated part and the app
#     controllable part. The suffix "<name> - N running windows" /
#     "<name> - N <localized token>" is generated by the shell in the SYSTEM
#     language, not in the app language, so it must never be compared between
#     the zh and en runs. TASKBAR_BUTTON_PREFIX is the part the app controls.
#   * reports a CROSS APPLICATION control. The shell can only show an
#     app-declared display name if it reads one at all, so the criterion is only
#     allowed to say FAIL when at least one OTHER application's AUMID-shaped
#     button (Edge / Windows Terminal / Feishu / ...) shows a name here.
#
# VERDICT RULE (W1b lesson, kept deliberately):
#   PROBE_VERDICT=FAIL may ONLY be printed when CONTROL_XAPP=PASS AND the target
#   button exists AND its name is readable-but-empty. In every other unhealthy
#   case the answer is UNPROVEN. A blind device must never produce a product
#   FAIL -- that is exactly how P-2 got its first wrong verdict.
#
# TWO STATE MODE (-TwoStateBaseline):
#   reads the button in both UI languages, in this order, and leaves the machine
#   in the state it found it:
#     zh (locale row ABSENT) -> read -> baseline_zh.txt
#     en (locale row = en)   -> read -> baseline_en.txt
#     restore                -> read -> MUST be ABSENT, else the run is flagged
#   Both readings are then written into baseline_two_state.txt as
#   TASKBAR_BUTTON_NAME_ZH= / TASKBAR_BUTTON_NAME_EN=, which is the before
#   baseline W1c-2 has to be compared against verbatim.
#   The locale switch uses the existing reports\task47-W1-install\locale.ps1
#   UNCHANGED (it is a read-only dependency of this script; that tool does write
#   its own locale.log and a db backup, and those side effects are registered in
#   the W1c-1 report).
#
# NEVER: writes product files, deletes files, uses pixels. Read only on the
# product; the only mutation is stopping/starting the app under test and the
# locale row, both required to observe the criterion.
#
# Usage:
#   pwsh -NoProfile -File tools\verify\task47_taskbar_button_name.ps1 -Language zh
#   pwsh -NoProfile -File tools\verify\task47_taskbar_button_name.ps1 -TwoStateBaseline
#   pwsh -NoProfile -File tools\verify\task47_taskbar_button_name.ps1 -MatchName ZZ-TB-TITLE-1
#
# ASCII only; every Chinese token is built from code points.

