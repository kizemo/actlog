# UIA returns a huge negative "infinite" rect for elements it cannot place.
# Casting that to [int] throws and kills the whole run (hit in W1b); every rect
# goes through here.
function Format-Rect($r) {
    try {
        $x = [double]$r.X; $y = [double]$r.Y; $w = [double]$r.Width; $h = [double]$r.Height
        foreach ($v in @($x, $y, $w, $h)) {
            if ([double]::IsNaN($v) -or [double]::IsInfinity($v) -or [math]::Abs($v) -ge 1e9) { return 'INFINITE' }
        }
        return ('({0},{1},{2},{3})' -f [int]$x, [int]$y, [int]$w, [int]$h)
    } catch { return 'INFINITE' }
}

# Pinned buttons carry a trailing marker in the SYSTEM language ("<token>" for
# pinned). It is shell chrome, not an app-declared string, so it is removed
# before the app controllable prefix is derived.
$script:PinnedTokens = @(
    ([string][char]0x5DF2 + [char]0x56FA + [char]0x5B9A),
    'pinned'
)

function Test-PinnedName([string]$Name) {
    if ([string]::IsNullOrWhiteSpace($Name)) { return $false }
    $n = $Name.Trim()
    foreach ($tok in $script:PinnedTokens) {
        if ($n.EndsWith($tok, [System.StringComparison]::OrdinalIgnoreCase)) { return $true }
    }
    return $false
}

# The app controllable part of the button name: everything before the LAST
# "<space>-<space><digits><space>" group suffix, with the pinned marker removed.
#   'actlog - 1 <cn windows>'                    -> 'actlog'
#   '<cn profile> 2 - Edge - 1 <cn windows>'     -> '<cn profile> 2 - Edge'
function Get-AppPrefix([string]$Name) {
    if ([string]::IsNullOrWhiteSpace($Name)) { return '' }
    $n = $Name.Trim()
    foreach ($tok in $script:PinnedTokens) {
        if ($n.EndsWith($tok, [System.StringComparison]::OrdinalIgnoreCase)) {
            $n = $n.Substring(0, $n.Length - $tok.Length).Trim()
        }
    }
    if ($n -match '^(.*)\s-\s\d+\s.+$') { return $Matches[1].Trim() }
    return $n
}

# locale.ps1 -Mode get always echoes a non-empty line: 'locale-row: <value>' when
# the row is set, 'locale-row: ABSENT' when it is not. Judging "absent" by an empty
# string therefore never matches, so look at the token after the colon instead.
function Test-LocaleRowAbsent([string]$Row) {
    if ([string]::IsNullOrWhiteSpace($Row)) { return $true }
    return [bool]($Row -match 'locale-row:\s*ABSENT')
}

function Get-TaskbarButtons {
    $hTray = [TBW.Win32]::FindWindow('Shell_TrayWnd', $null)
    if ($hTray -eq [IntPtr]::Zero) { return $null }
    $root = $UIAuto::FromHandle($hTray)
    if ($root -eq $null) { return $null }
    $all = $root.FindAll($UIScope, $UICond)
    $btns = New-Object 'System.Collections.Generic.List[object]'
    foreach ($e in $all) {
        try { $ct = $e.Current.ControlType.ProgrammaticName } catch { continue }
        if ($ct -ne 'ControlType.Button') { continue }
        try {
            $btns.Add([pscustomobject]@{
                Name  = $e.Current.Name
                Id    = $e.Current.AutomationId
                Class = $e.Current.ClassName
                Rect  = (Format-Rect $e.Current.BoundingRectangle)
            })
        } catch { continue }
    }
    return [pscustomobject]@{ Hwnd = $hTray; Descendants = $all.Count; Buttons = $btns }
}

function Test-TargetMatch($btn) {
    if (-not [string]::IsNullOrWhiteSpace($MatchName)) {
        if ([string]::IsNullOrWhiteSpace($btn.Name)) { return $false }
        return ($btn.Name.IndexOf($MatchName, [System.StringComparison]::OrdinalIgnoreCase) -ge 0)
    }
    if ([string]::IsNullOrWhiteSpace($ExePath)) { return $false }
    if ($btn.Id -ieq ('Appid: ' + $ExePath)) { return $true }
    if (-not [string]::IsNullOrWhiteSpace($btn.Id) -and
        $btn.Id.IndexOf($ExePath, [System.StringComparison]::OrdinalIgnoreCase) -ge 0) { return $true }
    return $false
}

# CROSS APPLICATION CONTROL.
# An exe-path fallback button proves nothing about what the shell can display;
# an AUMID-shaped button with a human name proves the shell really renders an
# app-declared display name on this machine. Two shapes are told apart:
#   'Appid: <drive>:\...\x.exe'   exe-path fallback  -> NOT a control
#   'Appid: com.vendor.app[!App]' declared AUMID     -> control
function Get-XappControls($buttons) {
    $res = New-Object 'System.Collections.Generic.List[object]'
    foreach ($b in $buttons) {
        if ([string]::IsNullOrWhiteSpace($b.Name)) { continue }
        $id = [string]$b.Id
        # A control must come from ANOTHER application. The app under test is
        # measured by this very run, so accepting it would be circular.
        if ($id -ieq ('Appid: ' + $SelfAumid)) { continue }
        if (-not $id.StartsWith('Appid: ', [System.StringComparison]::OrdinalIgnoreCase)) { continue }
        if ($id.IndexOf('\') -ge 0) { continue }
        if ($id.IndexOf('.') -lt 0 -and $id.IndexOf('!') -lt 0) { continue }
        $res.Add($b)
    }
    return $res
}

function Get-TargetProcs {
    $list = New-Object 'System.Collections.Generic.List[object]'
    foreach ($p in @(Get-Process -Name (Get-ActLogProcessNames) -ErrorAction SilentlyContinue)) {
        $path = ''
        try { $path = $p.Path } catch { $path = '' }
        $list.Add([pscustomobject]@{ Id = $p.Id; Path = $path })
    }
    return $list
}

function Stop-TargetProcs {
    $stopped = New-Object 'System.Collections.Generic.List[int]'
    foreach ($p in (Get-TargetProcs)) {
        try { Stop-Process -Id $p.Id -Force -ErrorAction Stop } catch { }
        $stopped.Add($p.Id)
        Say ('STOP_PID=' + $p.Id + ' PATH=' + $p.Path)
    }
    if ($stopped.Count -gt 0) { Start-Sleep -Milliseconds 900 }
    return $stopped
}

# One reading of the taskbar. Polls because the button only appears a moment
# after the first visible frame.
function Invoke-TaskbarRead {
    param([string]$Lang)
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $scan = $null
    $target = $null
    while ($sw.Elapsed.TotalSeconds -lt $StartupWaitSec) {
        $scan = Get-TaskbarButtons
        if ($scan -ne $null) {
            foreach ($b in $scan.Buttons) {
                if (Test-TargetMatch $b) { $target = $b; break }
            }
        }
        if ($target -ne $null) { break }
        Start-Sleep -Milliseconds 700
    }
    if ($scan -eq $null) { $scan = Get-TaskbarButtons }

    $res = [pscustomobject]@{
        Lang       = $Lang
        Found      = ($target -ne $null)
        Name       = ''
        Prefix     = ''
        Id         = ''
        Class      = ''
        Pinned     = $false
        Descendants = 0
        Buttons     = $null
        Controls    = $null
        WaitMs      = 0
    }
    if ($scan -ne $null) {
        $res.Descendants = $scan.Descendants
        $res.Buttons = $scan.Buttons
        $res.Controls = (Get-XappControls $scan.Buttons)
    }
    $res.WaitMs = [int][math]::Round($sw.Elapsed.TotalMilliseconds)
    if ($target -ne $null) {
        $res.Name = [string]$target.Name
        $res.Prefix = Get-AppPrefix $res.Name
        $res.Id = [string]$target.Id
        $res.Class = [string]$target.Class
        $res.Pinned = Test-PinnedName $res.Name
    }
    return $res
}

function Say-Buttons($read) {
    Say ('TASKBAR_DESCENDANTS=' + $read.Descendants)
    if ($read.Buttons -ne $null) {
        $i = 0
        foreach ($b in $read.Buttons) {
            Say ('BTN n=' + $i + " id='" + $b.Id + "' class='" + $b.Class + "' rect=" + $b.Rect + " name='" + $b.Name + "'")
            $i++
        }
    }
    if ($read.Controls -ne $null) {
        foreach ($c in $read.Controls) {
            Say ("CONTROL_XAPP_CANDIDATE id='" + $c.Id + "' name='" + $c.Name + "'")
        }
        Say ('CONTROL_XAPP_COUNT=' + $read.Controls.Count)
    } else {
        Say 'CONTROL_XAPP_COUNT=0'
    }
}

function Get-ControlVerdict($read) {
    if ($read.Controls -ne $null -and $read.Controls.Count -gt 0) { return 'PASS' }
    return 'FAIL'
}

function Get-ProbeVerdict($read, [string]$control) {
    if ($control -ne 'PASS') { return 'UNPROVEN' }
    if (-not $read.Found) { return 'UNPROVEN' }
    if ([string]::IsNullOrWhiteSpace($read.Name)) { return 'FAIL' }
    return 'PASS'
}

